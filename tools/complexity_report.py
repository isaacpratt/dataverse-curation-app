"""Advisory cyclomatic-complexity report for the engine and the UI.

The ruff `C901` gate (max-complexity 12) is the enforcement; this report is
the visibility that makes the burn-down legible: which functions are over
budget, how the average moves, and how maintainable the modules are.

Runs radon through `uv run --with radon` (no new dependency in the lockfile),
writes a markdown report to ``reports/complexity.md`` and prints a summary.
Advisory by default: exit 0 even when functions are over budget. Pass
``--fail-over`` to make it a gate.

Usage::

    uv run python tools/complexity_report.py            # report only
    uv run python tools/complexity_report.py --fail-over # exit 1 if over budget
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
REPORT_DIR = ROOT / "reports"
REPORT_PATH = REPORT_DIR / "complexity.md"
TARGETS = ("engine", "ui")
BUDGET = 12


def _radon_cc() -> list[dict[str, Any]]:
    """Run radon over the targets; returns its JSON blocks."""
    proc = subprocess.run(
        [
            "uv",
            "run",
            "--with",
            "radon",
            "radon",
            "cc",
            *TARGETS,
            "-j",
            "-s",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        print(f"radon cc failed: {proc.stderr.strip()[-500:]}", file=sys.stderr)
        return []
    try:
        data = json.loads(proc.stdout or "{}")
    except json.JSONDecodeError:
        print("radon cc returned unparsable JSON", file=sys.stderr)
        return []
    blocks: list[dict[str, Any]] = []
    for filename, entries in data.items():
        for entry in entries:
            blocks.append(
                {
                    "file": filename,
                    "name": entry.get("name"),
                    "type": entry.get("type"),
                    "line": entry.get("lineno"),
                    "complexity": int(entry.get("complexity") or 0),
                    "rank": entry.get("rank"),
                }
            )
    return blocks


def _radon_mi() -> dict[str, Any]:
    """Run radon's maintainability index; returns {file: mi}."""
    proc = subprocess.run(
        ["uv", "run", "--with", "radon", "radon", "mi", *TARGETS, "-j"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        return {}
    try:
        data = json.loads(proc.stdout or "{}")
    except json.JSONDecodeError:
        return {}
    return {name: float(value) for name, value in data.items() if isinstance(value, (int, float))}


def render_report(blocks: list[dict[str, Any]], mi: dict[str, Any]) -> str:
    """Render the markdown report for a radon run."""
    over = sorted(
        (b for b in blocks if b["complexity"] > BUDGET),
        key=lambda b: (-b["complexity"], b["file"], b["line"] or 0),
    )
    complexities = [b["complexity"] for b in blocks]
    average = sum(complexities) / len(complexities) if complexities else 0.0
    worst_files = sorted(mi.items(), key=lambda kv: kv[1])[:10]
    lines = [
        "# Complexity report (advisory)",
        "",
        "Generated by `tools/complexity_report.py` (radon). The enforcement gate is",
        f"ruff's `C901` (max-complexity {BUDGET}); this report shows the trend.",
        "",
        "radon and ruff count complexity differently and radon ignores `noqa`",
        "suppressions, so the two counts differ (radon sees more over-budget",
        "blocks). Use ruff's count for the gate, this one for the trend.",
        "",
        f"- blocks analysed: **{len(blocks)}**",
        f"- average complexity: **{average:.2f}**",
        f"- blocks over the budget (> {BUDGET}): **{len(over)}**",
        "",
        "## Over budget",
        "",
    ]
    if over:
        lines += ["| File | Function | Line | Complexity |", "|---|---|---|---|"]
        for block in over:
            rel = (
                Path(block["file"]).relative_to(ROOT)
                if Path(block["file"]).is_absolute()
                else block["file"]
            )
            lines.append(
                f"| `{rel}` | `{block['name']}` | {block['line']} | {block['complexity']} |"
            )
    else:
        lines.append("None — every block is within the budget.")
    lines += [
        "",
        "## Lowest maintainability index",
        "",
        "| File | MI |",
        "|---|---|",
    ]
    for name, value in worst_files:
        rel = Path(name).relative_to(ROOT) if Path(name).is_absolute() else name
        lines.append(f"| `{rel}` | {value:.1f} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    """Write the complexity report; exit 0 unless --fail-over is over budget."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fail-over",
        action="store_true",
        help="exit 1 when a block exceeds the complexity budget",
    )
    args = parser.parse_args()

    blocks = _radon_cc()
    if not blocks:
        print("complexity: radon produced no blocks", file=sys.stderr)
        return 1
    mi = _radon_mi()
    over = [b for b in blocks if b["complexity"] > BUDGET]
    average = sum(b["complexity"] for b in blocks) / len(blocks)

    REPORT_DIR.mkdir(exist_ok=True)
    REPORT_PATH.write_text(render_report(blocks, mi), encoding="utf-8")

    print(f"complexity: {len(blocks)} blocks, average {average:.2f}, {len(over)} over budget")
    for block in sorted(over, key=lambda b: -b["complexity"])[:10]:
        print(f"  {block['complexity']:>3}  {block['file']}:{block['line']} {block['name']}")
    print(f"complexity: report written to {REPORT_PATH}")
    if args.fail_over and over:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
